/// A line that morphs from the calm "anxious" curve ("A little")
/// into the tangled "anxious" scribble ("Very"), using the designer's SVG paths.
struct ScribbleShape: Shape {
    var intensity: Double

    var animatableData: Double {
        get { intensity }
        set { intensity = newValue }
    }

    func path(in rect: CGRect) -> Path {
        let t = min(max(intensity, 0), 1)
        let calm = ScribbleData.calm
        let tangled = ScribbleData.tangled

        // Each shape is fitted into its own area of the rect: the calm curve
        // is narrower and the tangle fills almost the whole width.
        let calmRect = fitted(aspect: ScribbleData.calmAspect, widthFraction: 0.75, in: rect)
        let tangledRect = fitted(aspect: ScribbleData.tangledAspect, widthFraction: 0.95, in: rect)

        func point(at index: Int) -> CGPoint {
            let a = calm[index], b = tangled[index]
            let start = CGPoint(x: calmRect.minX + a.x * calmRect.width, y: calmRect.minY + a.y * calmRect.height)
            let end = CGPoint(x: tangledRect.minX + b.x * tangledRect.width, y: tangledRect.minY + b.y * tangledRect.height)
            // Blend the matching points of both shapes so the curve crumples into the tangle.
            return CGPoint(x: start.x + (end.x - start.x) * t, y: start.y + (end.y - start.y) * t)
        }

        var path = Path()
        path.move(to: point(at: 0))
        for index in 1..<calm.count {
            path.addLine(to: point(at: index))
        }

        // Dots on both ends, as in the calm design, that fade away as the line tangles.
        let dotRadius = 2.5 * (1 - t)
        if dotRadius > 0.1 {
            for center in [point(at: 0), point(at: calm.count - 1)] {
                path.addEllipse(in: CGRect(
                    x: center.x - dotRadius, y: center.y - dotRadius,
                    width: dotRadius * 2, height: dotRadius * 2
                ))
            }
        }
        return path
    }

    /// The largest centered rect with the given aspect ratio that fits in `rect`
    /// and is at most `widthFraction` of its width.
    private func fitted(aspect: CGFloat, widthFraction: CGFloat, in rect: CGRect) -> CGRect {
        var width = rect.width * widthFraction
        var height = width / aspect
        if height > rect.height {
            height = rect.height
            width = height * aspect
        }
        return CGRect(x: rect.midX - width / 2, y: rect.midY - height / 2, width: width, height: height)
    }
}

