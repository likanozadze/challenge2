/// Reads SVG path data made of absolute `M` and `C` commands and samples it evenly along its length.
nonisolated enum SVGPathSampler {
    /// Points along the path, evenly spaced by distance, normalized to the path's bounding box.
    static func samples(of data: String, count: Int) -> [CGPoint] {
        let polyline = flatten(data)
        guard polyline.count > 1, count > 1 else { return polyline }

        // Cumulative distance along the polyline.
        var distances: [CGFloat] = [0]
        for i in 1..<polyline.count {
            distances.append(distances[i - 1] + hypot(polyline[i].x - polyline[i - 1].x, polyline[i].y - polyline[i - 1].y))
        }
        let total = distances[distances.count - 1]

        var result: [CGPoint] = []
        var segment = 1
        for i in 0..<count {
            let target = total * CGFloat(i) / CGFloat(count - 1)
            while segment < polyline.count - 1 && distances[segment] < target {
                segment += 1
            }
            let length = distances[segment] - distances[segment - 1]
            let f = length > 0 ? (target - distances[segment - 1]) / length : 0
            let a = polyline[segment - 1], b = polyline[segment]
            result.append(CGPoint(x: a.x + (b.x - a.x) * f, y: a.y + (b.y - a.y) * f))
        }
        return normalized(result, in: bounds(of: polyline))
    }

    /// Width divided by height of the path's bounding box.
    static func aspectRatio(of data: String) -> CGFloat {
        let box = bounds(of: flatten(data))
        return box.height > 0 ? box.width / box.height : 1
    }

    /// Turns the path into a dense polyline, approximating each cubic curve with short lines.
    private static func flatten(_ data: String) -> [CGPoint] {
        var points: [CGPoint] = []
        var current = CGPoint.zero
        var command: Character = "M"
        var numbers: [CGFloat] = []

        func flush() {
            switch command {
            case "M":
                var i = 0
                while i + 1 < numbers.count {
                    current = CGPoint(x: numbers[i], y: numbers[i + 1])
                    points.append(current)
                    i += 2
                }
            case "C":
                var i = 0
                while i + 5 < numbers.count {
                    let c1 = CGPoint(x: numbers[i], y: numbers[i + 1])
                    let c2 = CGPoint(x: numbers[i + 2], y: numbers[i + 3])
                    let end = CGPoint(x: numbers[i + 4], y: numbers[i + 5])
                    for step in 1...16 {
                        points.append(cubic(current, c1, c2, end, CGFloat(step) / 16))
                    }
                    current = end
                    i += 6
                }
            default:
                break
            }
            numbers.removeAll()
        }

        var token = ""
        func endNumber() {
            if let value = Double(token) { numbers.append(CGFloat(value)) }
            token = ""
        }
        for character in data {
            if character == "M" || character == "C" {
                endNumber()
                flush()
                command = character
            } else if character == "," || character.isWhitespace {
                endNumber()
            } else if character == "-" && !token.isEmpty && token.last != "e" {
                endNumber()
                token = "-"
            } else {
                token.append(character)
            }
        }
        endNumber()
        flush()
        return points
    }

    private static func cubic(_ p0: CGPoint, _ p1: CGPoint, _ p2: CGPoint, _ p3: CGPoint, _ t: CGFloat) -> CGPoint {
        let u = 1 - t
        let a = u * u * u, b = 3 * u * u * t, c = 3 * u * t * t, d = t * t * t
        return CGPoint(
            x: a * p0.x + b * p1.x + c * p2.x + d * p3.x,
            y: a * p0.y + b * p1.y + c * p2.y + d * p3.y
        )
    }

    private static func bounds(of points: [CGPoint]) -> CGRect {
        guard let first = points.first else { return .zero }
        var minX = first.x, maxX = first.x, minY = first.y, maxY = first.y
        for p in points {
            minX = min(minX, p.x); maxX = max(maxX, p.x)
            minY = min(minY, p.y); maxY = max(maxY, p.y)
        }
        return CGRect(x: minX, y: minY, width: maxX - minX, height: maxY - minY)
    }

    private static func normalized(_ points: [CGPoint], in box: CGRect) -> [CGPoint] {
        points.map { p in
            CGPoint(
                x: box.width > 0 ? (p.x - box.minX) / box.width : 0,
                y: box.height > 0 ? (p.y - box.minY) / box.height : 0
            )
        }
    }
}

